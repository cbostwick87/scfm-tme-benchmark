#!/usr/bin/env bash
# Periodically commit partial sweep results to the remote.
#
# WHY THIS EXISTS. The sweep is resumable from its own output, which protects
# against a crash. It does NOT protect against losing the instance: the results
# table lives only on the project volume, and the brief is explicit that access
# to this machine may end without notice. Losing compute costs time; losing
# results destroys the deliverable. A 30-hour run with nothing pushed for 30
# hours is a single point of failure that the resumability does not address.
#
# This commits the merged shards on a fixed interval, so the worst case is
# losing INTERVAL minutes of compute rather than the whole run. The table is
# small (a few MB at full size), well inside what belongs in git, and it is the
# actual deliverable rather than a regenerable intermediate.
#
# Usage:  scripts/checkpoint_results.sh [interval_seconds]
set +e
cd "$(dirname "$0")/.." || exit 1
INTERVAL="${1:-1800}"
export GIT_SSH_COMMAND="ssh -o StrictHostKeyChecking=accept-new"

while true; do
  sleep "$INTERVAL"

  # Merge shards into the canonical table before committing, so what is pushed
  # is always the same artefact the statistics stage consumes.
  python -c "
import pandas as pd, pathlib, sys
res = pathlib.Path('results')
shards = sorted(res.glob('T2_results_long.shard*.csv'))
if not shards:
    sys.exit(0)
d = pd.concat([pd.read_csv(f) for f in shards], ignore_index=True)
key = ['representation','split_file','budget','seed']
# keep only runs whose dataset rows are all present; a run interrupted
# mid-append must not enter the canonical table as a partial panel
counts = d.groupby(key).size()
exp = d.groupby(key)['n_datasets_in_run'].max()
good = counts[counts >= exp.reindex(counts.index)].index
d = d.set_index(key).loc[good].reset_index()
d.to_csv(res/'T2_results_long.csv', index=False)
print(f'{len(d)} rows / {len(good)} complete runs', flush=True)
" || continue

  N=$(python -c "
import pandas as pd
d=pd.read_csv('results/T2_results_long.csv')
print(d.groupby(['representation','split_file','budget','seed']).ngroups)
" 2>/dev/null) || continue
  [ -z "$N" ] && continue

  git add results/T2_results_long.csv
  git diff --cached --quiet && continue      # nothing new since last checkpoint
  git commit -q -m "checkpoint: ${N}/6750 sweep runs complete

Partial results committed automatically so the run survives loss of the
instance, not merely a crash. Regenerated by resuming the sweep; the table is
append-only and every run is keyed by (representation, split, budget, seed)."
  git push -q origin main 2>&1 | tail -2

  L=$(git rev-parse HEAD)
  R=$(git ls-remote origin refs/heads/main | cut -f1)
  if [ "$L" = "$R" ]; then
    echo "$(date -u +%FT%TZ) checkpoint pushed: ${N} runs, $L"
  else
    echo "$(date -u +%FT%TZ) WARNING push did not land (local $L != remote $R)"
  fi
done
